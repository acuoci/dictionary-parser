// An uncaught DictionaryError, reported by InstallErrorHandler. Run by CTest,
// which checks the report (the program exits with code 3).

#include "DictionaryDiagnostics.h"
#include "DictionaryManager.h"

#include <iostream>

int main() {
  OpenSMOKEpp::InstallErrorHandler(
      {.stream = &std::cout, .title = "Fatal error in the test input", .wait_for_enter = false, .exit_code = 3});
  OpenSMOKEpp::DictionaryManager manager;
  manager.ReadDictionariesFromString("Dictionary d { @X 1 }", "handler.dic"); // missing ';'
  return 0;
}
